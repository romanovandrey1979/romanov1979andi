def heat_loss():
    tr, ve = [], []
    for z, name, a, k in ENVELOPE:
        dt = ZONE_T[z] - T_EXT
        tr.append((z, name, round(a, 1), U[k], dt, a * U[k] * dt * 1.1 / 1000))
    for z, name, l, eta, share in VENT:
        dt = ZONE_T[z] - T_EXT
        ve.append((z, name, l, eta, dt, 0.34 * l * dt * (1 - eta) * share / 1000))
    q_tr = sum(r[5] for r in tr)
    q_ve = sum(r[5] for r in ve)
    q_inf = 0.08 * q_tr          # инфильтрация через ворота при открывании
    total = (q_tr + q_ve + q_inf) * 1.1
    return {"tr": tr, "ve": ve, "q_tr": q_tr, "q_ve": q_ve, "q_inf": q_inf, "total": total}


