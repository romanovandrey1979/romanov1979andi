def slab_check():
    g_n = sum(n for _, n, _ in LOADS)
    g_d = sum(n * f for _, n, f in LOADS)
    q_live = LIVE["Спортзал (свободные веса)"]
    q_d = g_d + q_live * 1.2
    w = q_d * RIB_STEP                          # кН/м на ребро
    M = w * RIB_SPAN ** 2 / 8 * 0.85            # неразрезность, коэффициент 0,85
    d = 0.60 - 0.05
    As = M * 1e6 / (435 * 0.9 * d * 1000)       # мм², A500
    bars = math.ceil(As / 380.1)                # Ø22
    # тавр: полка 1,5 м × 0,2, ребро 0,3 × 0,4
    bf, hf, bw, hw = 1.5, 0.20, 0.30, 0.40
    a1, y1 = bf * hf, hw + hf / 2
    a2, y2 = bw * hw, hw / 2
    yc = (a1 * y1 + a2 * y2) / (a1 + a2)
    I = bf * hf ** 3 / 12 + a1 * (y1 - yc) ** 2 + bw * hw ** 3 / 12 + a2 * (y2 - yc) ** 2
    Ieff = I * 0.5                               # трещинообразование
    w_qp = (g_n + 0.35 * q_live) * RIB_STEP * 1e3
    delta = 5 * w_qp * RIB_SPAN ** 4 / (384 * CONC_E * Ieff)
    w_dyn = (g_n + 0.1 * q_live) * RIB_STEP * 1e3
    delta_dyn = 5 * w_dyn * RIB_SPAN ** 4 / (384 * CONC_E * I)
    f1 = 18 / math.sqrt(delta_dyn * 1000)
    return {"g_n": g_n, "g_d": g_d, "q_d": q_d, "w": w, "M": M, "As": As, "bars": bars,
            "I": I, "delta_mm": delta * 1000, "delta_lim": RIB_SPAN * 1000 / 250, "f1": f1}


