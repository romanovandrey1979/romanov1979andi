def total(n):
    return n["flow"] + sum(total(c) for c in n["children"])


def segments(n, vmain=5.0, vbranch=3.0):
    """Список (точки ломаной, расход, диаметр, скорость) для дерева воздуховодов."""
    out = []
    for c in n["children"]:
        q = total(c)
        (x0, y0), (x1, y1) = n["pt"], c["pt"]
        mid = (x1, y0) if c["path"] == "hv" else (x0, y1)
        terminal = not c["children"]
        d, v = duct_d(q, vbranch if terminal or q < 120 else vmain)
        out.append(([n["pt"], mid, c["pt"]], q, d, v, c))
        out += segments(c, vmain, vbranch)
    return out


def walk(n):
    yield n
    for c in n["children"]:
        yield from walk(c)
