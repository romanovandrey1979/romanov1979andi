def ref(x, y):
    ax = min(AXES_X, key=lambda a: abs(AXES_X[a] - x))
    ay = min(AXES_Y, key=lambda a: abs(AXES_Y[a] - y))
    return f"{ax}/{ay}", f"{x - AXES_X[ax]:+d}", f"{y - AXES_Y[ay]:+d}"


