def kd4_openings():
    rows = []
    for name, s in G.SHAFTS.items():
        a, dx, dy = ref(*s["pt"])
        rows.append((name, "Вентиляционный короб: " + s["use"], a, dx, dy, s["size"], "1–2 эт., чердак"))
    for name, (pt, out, vent) in VK.STACKS.items():
        a, dx, dy = ref(*pt)
        rows.append((name, "Стояк канализации Ø110", a, dx, dy, "проём 200×200", "1–2 эт."
                     + (", кровля" if "кровл" in vent else ", чердак")))
    for name, pt in VK.WRISERS.items():
        a, dx, dy = ref(*pt)
        rows.append((name, "Стояк водопровода В1/Т3/Т4 (3 трубы в изоляции)", a, dx, dy,
                     "проём 200×150", "1–2 эт."))
    for name, pt in OV.RISERS.items():
        a, dx, dy = ref(*pt)
        rows.append((name, "Стояк отопления Т1/Т2 (в коробе)", a, dx, dy, "проём 150×100", "1–2 эт."))
    return rows


