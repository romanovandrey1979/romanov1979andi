# ------------------------------------------------------------------ XLSX
def make_xlsx(path):
    wb = Workbook()
    thin = Side(style="thin")
    brd = Border(left=thin, right=thin, top=thin, bottom=thin)
    hfill = PatternFill("solid", fgColor="DDDDDD")

    def put(ws, rows, widths):
        for r in rows:
            ws.append(list(r))
        for c, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(c)].width = w
        for row in ws.iter_rows(min_row=1, max_row=ws.max_row):
            for cell in row:
                cell.border = brd
                cell.alignment = Alignment(wrap_text=True, vertical="center")
        for cell in ws[1]:
            cell.font = Font(bold=True)
            cell.fill = hfill
        ws.freeze_panes = "A2"

    ws = wb.active
    ws.title = "Воздухообмен"
    rows = [("Этаж", "№", "Помещение", "S, м²", "h, м", "V, м³", "Приток, м³/ч", "Система",
             "Вытяжка, м³/ч", "Система", "Кратность притока", "Кратность вытяжки", "Обоснование")]
    for i, r in enumerate(ROOMS, 2):
        rows.append((r["floor"], r["num"], r["name"], r["area"], r["h"], f"=D{i}*E{i}",
                     r["sup"], r["sup_sys"], r["exh"], r["exh_sys"],
                     f"=IF(F{i}>0,G{i}/F{i},0)", f"=IF(F{i}>0,I{i}/F{i},0)", r["basis"]))
    n = len(ROOMS) + 1
    rows.append(("", "", "Итого П1", "", "", "", f'=SUMIF(H2:H{n},"П1",G2:G{n})', "П1", "", "",
                 "", "", ""))
    rows.append(("", "", "Итого В1", "", "", "", "", "", f'=SUMIF(J2:J{n},"В1",I2:I{n})', "В1",
                 "", "", ""))
    put(ws, rows, [6, 5, 32, 8, 7, 9, 11, 9, 11, 9, 10, 10, 50])
    for row in ws.iter_rows(min_row=2, min_col=11, max_col=12):
        for c in row:
            c.number_format = "0.00"
    for row in ws.iter_rows(min_row=2, min_col=6, max_col=6):
        for c in row:
            c.number_format = "0.0"

    ws = wb.create_sheet("Системы")
    t_after, q1 = p1_heater()
    q2 = p2_heater()
    rows = [("Система", "L, м³/ч", "Магистраль Ø, мм", "v, м/с", "Примечание")]
    for s in ("П1", "В1", "П2", "В3", "В2", "ЕВ1", "ПЕ1"):
        d, v = duct_d(TOT[s], 5.0 if s not in ("ЕВ1", "ПЕ1") else 1.2)
        rows.append((s, TOT[s], d, v, ""))
    rows.append(("", "", "", "", ""))
    rows.append(("Нагрев П1", "", "", "", f"η рекуператора={ETA_ROTOR}; t после рекуп.="
                 f"{t_after:.1f} °C; Q=0,336·L·Δt={q1:.2f} кВт"))
    rows.append(("Нагрев П2", "", "", "", f"от {CLIMATE['t_winter']:.0f} до +16 °C; Q={q2:.2f} кВт"))
    put(ws, rows, [14, 10, 18, 10, 80])

    ws = wb.create_sheet("Кондиционирование")
    rows = [("Марка", "Этаж", "№", "Помещение", "S, м²", "q, Вт/м²", "Люди", "Q люди, Вт",
             "Q оборуд., Вт", "Qрасч, кВт", "Блок, кВт", "Тип", "Система")]
    for i, a in enumerate(AC, 2):
        rows.append((a["mark"], a["floor"], a["num"], a["name"], a["area"], COOL_Q[a["kind"]],
                     a["n"], f"=G{i}*{PEOPLE_W}", 800 if a["kind"] == "kitchen" else 0,
                     f"=(E{i}*F{i}+H{i}+I{i})/1000", a["unit"], a["unit_type"],
                     "К1" if a["floor"] == 1 else "К2"))
    rows.append(("", "", "", "", "", "", "", "", "", "", "", "", ""))
    for s in AC_SYS:
        rows.append((s["sys"], "", "", "Наружный блок", "", "", "", "", "",
                     s["q"], s["outdoor"], f"ΣВБ={s['sum_units']} кВт, загрузка {s['ratio']}%", ""))
    put(ws, rows, [8, 6, 5, 30, 8, 9, 7, 10, 11, 10, 9, 28, 9])

    ws = wb.create_sheet("Спецификация")
    rows = [("Поз.", "Наименование и техническая характеристика", "Тип, марка", "Ед.", "Кол.",
             "Примечание")]
    for r in spec_rows():
        if r[0] == "#":
            rows.append(("", r[1], "", "", "", ""))
        else:
            rows.append(r)
    put(ws, rows, [8, 90, 28, 8, 8, 32])
    for row in ws.iter_rows(min_row=2):
        if row[0].value == "" and row[1].value and not row[3].value:
            row[1].font = Font(bold=True)
    wb.save(path)


