def alpha(np_):
    if np_ <= ALPHA[0][0]:
        return ALPHA[0][1]
    for (a, va), (b, vb) in zip(ALPHA, ALPHA[1:]):
        if a <= np_ <= b:
            return va + (np_ - a) / (b - a) * (vb - va)
    return ALPHA[-1][1]


def water_calc():
    N = sum(1 for f in FIXTURES if f[3] > 0)
    Nh = sum(1 for f in FIXTURES if f[4] > 0)
