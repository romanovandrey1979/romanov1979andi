# Стороны плана → реальная ориентация по стрелке «С» на листе 3 АПР (север ≈ 26° ниже
# левого края листа): верх плана — ВЮВ (≈116°), право — ЮЮЗ (≈206°), низ — ЗСЗ (≈296°),
# лево — ССВ (≈26°). Буквы С/В/Ю/З в данных ниже — стороны листа (верх/право/низ/лево).
ORIENT = {"С": "ВЮВ", "В": "ЮЮЗ", "Ю": "ЗСЗ", "З": "ССВ"}
BETA = {"С": 0.05, "В": 0.0, "Ю": 0.10, "З": 0.10}   # СП 50 / СП 60: ЮВ, З — 5 %; Ю, ЮЗ — 0; СЗ, С — 10 %
INFILTR_ACH = 0.15     # инфильтрация при сбалансированной механической вентиляции


def heat_losses(wall_key="wall"):
    Rw, Rwin, Rr = R0(wall_key), R0("window"), R0("roof")
    Rf1, Rfa = R0("floor1"), R0("floor_air")
    n_f1 = CONSTRUCTIONS["floor1"]["n"]
    res = []
    for fl, num, name, S, t, finish, walls, wins, f_air, roof in ROOMS:
        h = H1 if fl == 1 else H2
        dt = t - T_OUT
        win_by = {}
        for o, a in wins:
            win_by[o] = win_by.get(o, 0) + a
        q_wall = q_win = 0
        A_wall = A_win = 0
        for o, L in walls:
            aw = win_by.get(o, 0)
            ao = max(L * h - aw, 0)
            q_wall += ao / Rw * dt * (1 + BETA[o])
            q_win += aw / Rwin * dt * (1 + BETA[o])
            A_wall += ao
            A_win += aw
        q_floor = (S / Rf1 * dt * n_f1) if fl == 1 else (f_air / Rfa * dt)
        q_roof = roof * ROOF_K / Rr * dt
        V = S * (3.7 if fl == 1 else 3.4) if num != 1 or fl != 2 else 28.8 * 3.4
        q_inf = 0.336 * INFILTR_ACH * V * dt
        q = q_wall + q_win + q_floor + q_roof + q_inf
        res.append(dict(floor=fl, num=num, name=name, area=S, t=t, finish=finish,
                        A_wall=A_wall, A_win=A_win, q_wall=q_wall, q_win=q_win,
                        q_floor=q_floor, q_roof=q_roof, q_inf=q_inf, q=q))
    return res


# ---------------------------------------------------------------- тёплый пол
# удельная теплоотдача пола при 40/32 °C, шаг 150 мм, Вт/м² активной площади
Q_FLOOR = {"плитка": 85, "дерево": 55}
ACTIVE = 0.85         # доля площади под трубами (за вычетом мебели/шкафов)
NO_FLOOR = {(1, 5), (2, 6)}      # котельная (тепловыделения котла), кладовая 2 эт.
LOOP_MAX = 90         # м, максимальная длина петли PE-Xa 16×2
PIPE_PER_M2 = 6.7     # м трубы на м² при шаге 150 мм


def heating_plan(losses):
    plan = []
    for r in losses:
        key = (r["floor"], r["num"])
        q_floor = 0 if key in NO_FLOOR else Q_FLOOR[r["finish"]] * r["area"] * ACTIVE
        q_floor = min(q_floor, r["q"] * 1.15)
        rest = max(r["q"] - q_floor, 0)
        dev = ""
        if key == (1, 5):
            dev, rest = "Тепловыделения котла и трубопроводов", 0
        elif key == (1, 11):
            dev, rest = "", 0          # сауна: фоновый тёплый пол, добор — электропечь
        elif r["A_win"] >= 6:
            dev = "Конвектор внутрипольный"
        elif rest > 120 and "С/У" in r["name"]:
            dev = "Полотенцесушитель водяной"
        elif rest > 120:
            dev = "Радиатор стальной панельный"
        else:
            rest = 0
        loops = 0 if q_floor == 0 else max(1, math.ceil(r["area"] * ACTIVE * PIPE_PER_M2 / LOOP_MAX))
        plan.append(dict(r, q_floor_sys=q_floor, q_extra=rest, device=dev, loops=loops,
                         pipe=r["area"] * ACTIVE * PIPE_PER_M2 if q_floor else 0))
    return plan


