def mixed_lambda(f_wood, lam_ins=0.042, lam_wood=0.18):
    """Эквивалентная λ для слоя «утеплитель + деревянные элементы» (параллельно)."""
    return (1 - f_wood) * lam_ins + f_wood * lam_wood


def R_layers(key):
    c = CONSTRUCTIONS[key]
    out = []
    for nm, d, lam, note in c["layers"]:
        if lam is None:
            f = 0.078 if key == "roof" else 0.06
            lam = mixed_lambda(f)
        out.append((nm, d, lam, d / lam, note))
    return out


def R0(key):
    c = CONSTRUCTIONS[key]
    if key == "window":
        return c["R"]
    rc = sum(x[3] for x in R_layers(key))
    return (1 / c["a_in"] + rc + 1 / c["a_out"]) * c["r"]


def R_req(key):
    c = CONSTRUCTIONS[key]
    a, b = c["req"]
    return a * GSOP + b


