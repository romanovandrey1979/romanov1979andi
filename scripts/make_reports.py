def budget():
    items = budget_items()
    sub_min = sum(a for _, its in items for _, a, _b in its)
    sub_max = sum(b for _, its in items for _, _a, b in its)
    res_min, res_max = round(sub_min * 0.07, -1), round(sub_max * 0.07, -1)
    d = Doc("Бюджет строительства дома «Берта Ромарио» (укрупнённая оценка)",
            "Цены — ориентировочные для Московского региона, 2026–2027 гг., тыс. ₽ с НДС, "
            "оборудование среднего сегмента. Не является сметой; точные цифры — по КП подрядчиков "
            "и поставщиков.")
    rows = [("Раздел / статья", "Мин., тыс. ₽", "Макс., тыс. ₽")]
    for g, its in items:
        gmin = sum(a for _, a, _b in its)
        gmax = sum(b for _, _a, b in its)
        rows.append((g.upper(), f"{gmin:,}".replace(",", " "), f"{gmax:,}".replace(",", " ")))
        for nm, a, b in its:
            rows.append(("   " + nm, f"{a:,}".replace(",", " "), f"{b:,}".replace(",", " ")))
