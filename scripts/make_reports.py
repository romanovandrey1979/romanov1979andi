def budget_items():
    """Единый источник — make_prefinish (под чистовую) + этапы после. Суммы в тыс. ₽."""
    import make_prefinish as PF
    t = lambda x: int(round(x / 1000, -1))
    groups = {}
    for g, n, lo, hi, note in PF.blocks():
        gname = {"Коробка": "Коробка и общестроительные работы", "Инженерия": "Инженерные системы",
                 "Организация": "Проекты, надзор, стройплощадка"}[g]
        groups.setdefault(gname, []).append((n, t(lo), t(hi)))
    items = list(groups.items())
    items.append(("После чистовой (отделка, сантехника, участок, газ 2028)",
                  [(n, t(lo), t(hi)) for n, lo, hi in PF.LATER]))
    return items


