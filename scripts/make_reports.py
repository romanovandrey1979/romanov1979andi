def budget_xlsx(path, items):
    wb = Workbook()
    ws = wb.active
    ws.title = "Бюджет"
    thin = Side(style="thin")
    brd = Border(left=thin, right=thin, top=thin, bottom=thin)
    ws.append(["Раздел / статья", "Мин., тыс. ₽", "Макс., тыс. ₽", "Среднее, тыс. ₽"])
    for c in ws[1]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="DDDDDD")
    group_rows = []
    for g, its in items:
        r0 = ws.max_row + 1
        ws.append([g, None, None, None])
        first = r0 + 1
        for nm, a, b in its:
            r = ws.max_row + 1
            ws.append([nm, a, b, f"=(B{r}+C{r})/2"])
        last = ws.max_row
        for col in "BCD":
            ws[f"{col}{r0}"] = f"=SUM({col}{first}:{col}{last})"
            ws[f"{col}{r0}"].font = Font(bold=True)
        ws[f"A{r0}"].font = Font(bold=True)
        group_rows.append(r0)
    r = ws.max_row + 1
    ws.append(["Непредвиденные расходы 10–15 % (кроме договора СХ)",
               f"=ROUND(0.10*({'+'.join('B' + str(x) for x in group_rows)}-43500),-1)",
               f"=ROUND(0.15*({'+'.join('C' + str(x) for x in group_rows)}-43500),-1)", f"=(B{ws.max_row + 1}+C{ws.max_row + 1})/2"])
    r2 = ws.max_row + 1
    ws.append(["ИТОГО"] + [f"={'+'.join(c + str(x) for x in group_rows)}+{c}{r}" for c in "BCD"])
    for c in ws[r2]:
        c.font = Font(bold=True)
    ws.column_dimensions["A"].width = 90
    for col in "BCD":
        ws.column_dimensions[col].width = 16
    for row in ws.iter_rows(min_row=1, max_row=ws.max_row):
        for c in row:
            c.border = brd
            c.alignment = Alignment(wrap_text=True, vertical="center")
            if c.column > 1:
                c.number_format = "# ##0"
    wb.save(path)


def budget_csv(items, res, tot):
    b = io.StringIO()
    w = csv.writer(b)
    w.writerow(["Раздел / статья", "Мин., тыс. ₽", "Макс., тыс. ₽"])
    for g, its in items:
        w.writerow([g.upper(), sum(a for _, a, _b in its), sum(bb for _, _a, bb in its)])
        for nm, a, bb in its:
            w.writerow(["   " + nm, a, bb])
    w.writerow(["Непредвиденные расходы 10–15 % (кроме договора СХ)", int(res[0]), int(res[1])])
    w.writerow(["ИТОГО ПОД КЛЮЧ", int(tot[0]), int(tot[1])])
    return b.getvalue()


