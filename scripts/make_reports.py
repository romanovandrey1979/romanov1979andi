def gantt(path):
    fig, ax = plt.subplots(figsize=(11.5, 8.2))
    colors_g = {"Подготовка": "#90a4ae", "Нулевой цикл": "#8d6e63", "Коробка": "#a1887f",
                "Сети": "#4db6ac", "Инженерия": "#e57373", "Фасад и участок": "#81c784",
                "Отделка": "#ffb74d", "Ввод": "#64b5f6", "Газ": "#ba68c8"}
    for i, (g, nm, start, days, ms) in enumerate(TASKS):
        s = dt.date.fromisoformat(start)
        y = len(TASKS) - i
        if ms:
            ax.plot(mdates.date2num(s), y, marker="D", ms=8, c="k")
        else:
            ax.barh(y, days, left=mdates.date2num(s), height=0.6, color=colors_g[g],
                    edgecolor="k", lw=0.4)
        ax.text(mdates.date2num(dt.date(2026, 10, 1)) - 4, y, nm, ha="right", va="center",
                fontsize=6.6)
    ax.set_yticks([])
    ax.xaxis_date()
    ax.xaxis.set_major_locator(mdates.MonthLocator())
    ax.xaxis.set_major_formatter(mdates.DateFormatter("%m.%y"))
    plt.setp(ax.get_xticklabels(), fontsize=6.5, rotation=90)
    ax.set_xlim(mdates.date2num(dt.date(2026, 10, 1)), mdates.date2num(dt.date(2028, 7, 15)))
    ax.grid(axis="x", lw=0.3)
    for g, c in colors_g.items():
        ax.barh(-5, 1, color=c, label=g)
    ax.set_ylim(0, len(TASKS) + 1)
    ax.legend(fontsize=6.5, loc="lower left", ncol=3, frameon=False)
    ax.set_title("График строительства дома «Берта Ромарио» (ориентировочный)", fontsize=10)
    plt.subplots_adjust(left=0.42, right=0.98, top=0.95, bottom=0.08)
    fig.savefig(path, dpi=170)
    plt.close(fig)


