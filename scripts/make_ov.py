def devices(ax, floor):
    for d in DEV:
        if d["floor"] != floor:
            continue
        key = (d["floor"], d["num"])
        if d["dev"] != RAD and key in CONV_SEG:
            segs = CONV_SEG[key]
            per = [d["n"] // len(segs) + (1 if i < d["n"] % len(segs) else 0)
                   for i in range(len(segs))]
            for (xa, ya, xb, yb), n in zip(segs, per):
                for i in range(n):
                    t = (i + 0.5) / n
                    cx, cy = xa + (xb - xa) * t, ya + (yb - ya) * t
                    horiz = abs(yb - ya) < 1
                    w, h = (14, 2.4) if horiz else (2.4, 14)
                    sx, sy = S((cx, cy))
                    ax.add_patch(Rectangle((sx - w / 2, sy - h / 2), w, h, fc="#ffcdd2", ec=RED,
                                           lw=0.8, zorder=6, ls="-" if floor == 1 else "--"))
            sx, sy = S((segs[0][0], segs[0][1]))
            tag = "ВК" if floor == 1 else "НК"
            kind = "вент." if "вентил" in d["dev"] else ("ест." if floor == 1 else "низк.")
            ax.text(sx, sy + 2.2, f"{tag} ×{d['n']} по {d['unit']} Вт ({kind})", fontsize=4.2,
                    color=RED, zorder=9, bbox=dict(fc="white", ec="none", pad=0.1, alpha=0.85))
        else:
            x0, y0, x1, y1 = GEOM[key]
            sx, sy = S((x0 + 500, y0 + 400))
            ax.add_patch(Rectangle((sx - 4, sy - 1), 8, 2, fc="#ffcdd2", ec=RED, lw=0.8, zorder=6))
            ax.text(sx + 4.5, sy, f"Р {d['unit']} Вт", fontsize=4.2, color=RED, va="center",
                    zorder=9, bbox=dict(fc="white", ec="none", pad=0.1, alpha=0.85))


