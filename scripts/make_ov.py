def build_plan():
    plan = []
    for r in LOSSES:
        key = (r["floor"], r["num"])
        ufh = 0.0
        if r["floor"] == 1 and key not in NO_UFH:
            ufh = r["area"] * ACTIVE * (UFH_W_WET if key == (1, 13) else UFH_W)
        el = EL_UFH.get(key, 0)
        towel = TOWEL_EL if key in EL_UFH else 0
        deficit = max(r["q"] - min(ufh, r["q"]) - (el + towel if el else 0), 0)
        dev, n = DEVICE_PLAN.get(key, ("", 0))
        note = ""
        if key == (1, 5):
            deficit, note = 0, "Тепловыделения котлов и трубопроводов"
        elif key == (1, 11):
            deficit, note = 0, "Электропечь 9 кВт (291-ЭОМ); фон — от соседних помещений"
        elif el:
            note = f"Эл. ТП {el} Вт + эл. полотенцесушитель {TOWEL_EL} Вт"
        elif not dev and deficit > 0:
            note = "Переток / теплоотдача ТП"
            deficit = 0
        unit = math.ceil(deficit / n * 1.1 / 50) * 50 if n else 0
        loops = (max(1, math.ceil(r["area"] * ACTIVE * PIPE_PER_M2 / LOOP_MAX)) if ufh else 0)
        plan.append(dict(r, ufh=ufh, el=el, towel=towel, deficit=deficit, dev=dev, n=n,
                         unit=unit, loops=loops, note=note,
                         pipe=r["area"] * ACTIVE * PIPE_PER_M2 if ufh else 0))
    return plan


