def room_label(ax, p, ktp):
    x0, y0, x1, y1 = GEOM[(p["floor"], p["num"])]
    cx, cy = S(((x0 + x1) / 2, (y0 + y1) / 2))
    if p["q_floor_sys"] > 0:
        x0s, y0s = S((x0 + 150, y0 + 150))
        x1s, y1s = S((x1 - 150, y1 - 150))
        ax.add_patch(Rectangle((x0s, y0s), x1s - x0s, y1s - y0s, fc=(1, 0.6, 0.2, 0.10),
                               ec=ORANGE, lw=0.5, ls="--", hatch="////", zorder=2))
    txt = f"{p['num']}. t={p['t']}°C\nQ={p['q'] / 1000:.2f} кВт"
    if p["q_floor_sys"] > 0:
        txt += f"\nТП {p['q_floor_sys'] / 1000:.2f} кВт, {p['loops']} петл.\n{ktp}"
    ax.text(cx, cy, txt, ha="center", va="center", fontsize=4.3, color=BROWN, zorder=8,
            bbox=dict(fc="white", ec=ORANGE, lw=0.4, pad=0.6, alpha=0.9))


def convectors(ax, floor):
    for d in DEV:
        if d["floor"] != floor:
            continue
        key = (d["floor"], d["num"])
        if d["kind"].startswith("Конвектор") and key in CONV_SEG:
            segs = CONV_SEG[key]
            per = [d["n"] // len(segs) + (1 if i < d["n"] % len(segs) else 0)
                   for i in range(len(segs))]
            for (xa, ya, xb, yb), n in zip(segs, per):
                for i in range(n):
                    t = (i + 0.5) / n
                    cx, cy = xa + (xb - xa) * t, ya + (yb - ya) * t
                    horiz = abs(yb - ya) < 1
                    w, h = (20, 2.6) if horiz else (2.6, 20)
                    sx, sy = S((cx, cy))
                    ax.add_patch(Rectangle((sx - w / 2, sy - h / 2), w, h, fc="#ffcdd2", ec=RED,
                                           lw=0.8, zorder=6))
            sx, sy = S((segs[0][0], segs[0][1]))
            ax.text(sx, sy + 2.2, f"К ×{d['n']} ({'вент.' if 'вентил' in d['kind'] else 'ест.'})",
                    fontsize=4.3, color=RED, zorder=9,
                    bbox=dict(fc="white", ec="none", pad=0.1, alpha=0.85))
        else:
            x0, y0, x1, y1 = GEOM[key]
            sx, sy = S((x0 + 500, y0 + 400))
            ax.add_patch(Rectangle((sx - 4, sy - 1), 8, 2, fc="#ffcdd2", ec=RED, lw=0.8, zorder=6))
            short = "ПС" if "Полотенце" in d["kind"] else "Р"
            ax.text(sx + 4.5, sy, f"{short} {round(d['unit'], -1):.0f} Вт", fontsize=4.2, color=RED,
                    va="center", zorder=9, bbox=dict(fc="white", ec="none", pad=0.1, alpha=0.85))


def ktp(ax, name, floor):
    x, y = S(KTP_PT[name])
