"""Ответы заказчика на вопросы руководства посёлка по инженерным разделам 291 (21.10.2026)."""
import os
import sys

import eom_data as E
import passport as PS
from docbuild import Doc
from ovk_spec import AC_SYS, HUMID
from ovk_data import X_IN, X_OUT, STEAM_KW_PER_KG

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "Заключение")


def c(x, n=1):
    return f"{x:.{n}f}".replace(".", ",")


def build():
    scen = dict(E.SCEN)
    gen_need = [v for k, v in E.SCEN if k.startswith("Авария")][0]
    hum_need = sum(h["g"] for h in HUMID)
    hum_cap = sum(h["cap"] for h in HUMID)
    hum_kw = sum(h["kw"] for h in HUMID)

    d = Doc("Ответы на вопросы по инженерным разделам — дом «Ромарио»",
            "Посёлок «Берта», г. о. Истра, участок 1. Ответ заказчика на вопросы руководства посёлка "
            "по разделам 291-ОВК, 291-ЭОМ, 291-МЗ.ПС, 291-ВК (ред. 21.10.2026). Разделы — концепт "
            "заказчика и исходные данные для проектировщика инженерных систем; окончательные "
            "подборы оборудования — на стадии РД.")

    # 1 ------------------------------------------------------------------------------------------
    d.h1("1. К1 и К2 — электрическая или холодильная мощность?")
    d.p(f"Холодильная. К1 ≈ {PS.AC['k1_kw']} кВт и К2 ≈ {PS.AC['k2_kw']} кВт — номинальная "
        "холодопроизводительность наружных блоков VRF-систем. Она подобрана по сумме теплопритоков "
        "помещений (солнце, люди, техника, освещение) с проверкой суммы номиналов канальных "
        "внутренних блоков. Электрическая мощность, которую блоки берут из сети, примерно в "
        "3 раза меньше (холодильный коэффициент EER ≈ 3,1–3,3) и заложена в 291-ЭОМ отдельно.")
    rows = [("Система", "Помещения", "Теплопритоки, кВт (с одновременностью)", "Сумма внутренних блоков, кВт",
             "Наружный блок, кВт холода", "Электрическая, кВт")]
    el = {"К1": 6.5, "К2": 4.3}
    for s in AC_SYS:
        rooms = ", ".join(u["name"].split(" (")[0] for u in s["units"])
        rows.append((s["sys"], f"{len(s['units'])} блоков: {rooms}", f"{c(s['q'])} ({c(s['q_div'])})",
                     c(s["sum_units"]), c(s["outdoor"], 0), c(el[s["sys"]])))
    rows.append(("Итого", "11 канальных блоков", f"{c(sum(s['q'] for s in AC_SYS))}",
                 c(sum(s["sum_units"] for s in AC_SYS)), c(sum(s["outdoor"] for s in AC_SYS), 0),
                 c(sum(el.values()))))
    d.table(rows, [0.8, 3.6, 1.6, 1.3, 1.3, 1.2], bold_last=True)
    d.small("Электрическая мощность — на одну систему в режиме охлаждения, по типовым данным VRF "
            "этого класса; уточняется по паспорту выбранной модели. В балансе дома (291-ЭОМ) "
            "наружные блоки учтены с коэффициентом 0,8 только в летнем режиме: лето — "
            f"{c(scen['Лето (кондиционирование, сауна, ТЭН ГВС)'])} кВт при выделенных 30 кВт.")

    # 2 ------------------------------------------------------------------------------------------
    d.h1("2. Паровое увлажнение 6 зон — расчёт мощности")
    d.p("Да, расчёт есть (291-ОВК, расчётная записка и лист увлажнения). Принята не одна "
        "центральная парогенераторная установка, а 6 зональных электродных пароувлажнителей "
        "ПУ1–ПУ6 на тёплом чердаке — каждый в своём приточном воздуховоде, со своим "
        "гигростатом в помещении. Так спальни регулируются независимо и выход из строя одного "
        "прибора не оставляет без увлажнения весь дом. Вода — после обратного осмоса "
        "(меньше накипи, дольше служат цилиндры).")
    d.p(f"Расчёт: G = L · ρ · (dв − dн) / 1000, кг/ч, где L — расход приточного воздуха в зону, "
        f"ρ = 1,2 кг/м³, dн = {c(X_OUT)} г/кг (наружный воздух −25 °C), dв = {c(X_IN)} г/кг "
        "(+22 °C, 40 %). Электрическая мощность — "
        f"{c(STEAM_KW_PER_KG, 2)} кВт на 1 кг/ч пара.")
    rows = [("Марка", "Зона", "Приток, м³/ч", "Нужно пара, кг/ч", "Прибор, кг/ч", "Эл. мощность, кВт")]
    for h in HUMID:
        rows.append((h["mark"], h["zone"], str(h["flow"]), c(h["g"], 2), c(h["cap"]), c(h["kw"], 2)))
    rows.append(("Итого", "", str(sum(h["flow"] for h in HUMID)), c(hum_need, 1), c(hum_cap),
                 c(hum_kw, 1)))
    d.table(rows, [0.8, 3.8, 1.1, 1.3, 1.1, 1.3], bold_last=True)
    d.small(f"Суммарная потребность {c(hum_need)} кг/ч, установлено {c(hum_cap)} кг/ч — запас на "
            "минимальные типоразмеры приборов и на морозы ниже расчётных. Электрическая мощность "
            f"{c(hum_kw)} кВт, две группы на чердачном щите ЩВ (ПУ1–ПУ3 и ПУ4–ПУ6). Увлажнители "
            "питаются только от сети: при аварии и на генераторе отключаются. Если выбрать "
            "один центральный парогенератор, нужен прибор 6–8 кг/ч, 5–6 кВт, с разводкой пара "
            "по 6 воздуховодам и зональными клапанами.")

    # 3 ------------------------------------------------------------------------------------------
    d.h1("3. Почему свой генератор всего 8–10 кВт")
    d.p("Генератор — не второй ввод на весь дом, а резерв для того, без чего дом не может "
        "оставаться при отключении сети. Электрические нагрузки дома разделены в 291-ЭОМ на три "
        "секции:")
    d.table([
        ("Секция", "Что входит", "Установленная, кВт", "От чего работает при аварии"),
        ("Бесперебойная", "Котельная (розжиг и шнек пеллетного котла, 5 насосов, автоматика), "
         "освещение, розетки, холодильники, слаботочка и охрана, водоснабжение, ворота",
         c(E.SECTIONS["бесперебойная"]), "Батарея 15 кВт·ч через инвертор 10–12 кВт мгновенно, "
         "затем генератор"),
        ("Гарантированная", "Вентиляция П1/В1, П2, вытяжки, наружное освещение",
         c(E.SECTIONS["гарантированная"]), "Генератор через АВР"),
        ("Общая", "Электрокотёл 12 кВт, ТЭН бойлера, кондиционеры, сауна, тёплые полы, "
         "увлажнители, зарядка электромобиля", c(E.SECTIONS["общая"]), "Только от сети"),
    ], [1.3, 4.8, 1.2, 2.5])
    d.p(f"Расчётная мощность первых двух секций с одновременностью — {c(gen_need)} кВт, поэтому "
        "генератор 8–10 кВт. Главное: отопление при аварии не зависит от электричества — "
        "работает пеллетный котёл, которому нужно около 1,2 кВт на автоматику и насосы, а "
        "буфер 1 000 л держит тепло несколько часов. Батарея 15 кВт·ч закрывает короткие "
        "отключения без запуска генератора (котельная, свет, связь — на 8–12 часов).")
    d.p("Генератор на полную мощность дома (30 кВт) нужен только для того, чтобы при аварии "
        "работали электрокотёл, кондиционеры и сауна. Это генератор в 3 раза дороже, "
        "громче и больше, с отдельным фундаментом и топливом, а работать ему придётся несколько "
        "часов в год. Если посёлок построит общую ДГУ с резервом на все дома, свой генератор "
        "остаётся только последним резервом или исключается. Вопрос к посёлку: планируется ли "
        "посёлковая ДГУ и на какую мощность на дом.")

    # 4 ------------------------------------------------------------------------------------------
    d.h1("4. Что значит «заземление от сваи»")
    d.p("Железобетонные сваи стоят в грунте на глубине 3–4 м, где грунт не промерзает и "
        "остаётся влажным. Их арматура — хороший естественный заземлитель (ПУЭ п. 1.7.109 "
        "разрешает использовать арматуру железобетонных фундаментов). «Заземление от сваи» "
        "означает: к арматуре двух свай З20 и З21 у котельной после срубки оголовков "
        "приваривается стальная полоса 40×4, которая выводится в котельную на главную "
        "заземляющую шину ГЗШ. Это нужно сделать до бетонирования плиты — потом доступа "
        "к сваям не будет.")
    d.p("Основной заземлитель — наружный контур: горизонтальная полоса 40×4 по периметру "
        "дома за отмосткой на глубине не менее 0,7 м и вертикальные электроды. К нему же "
        "присоединены токоотводы молниезащиты. Выпуски от свай дополняют контур и "
        "снижают сопротивление. Выпусков арматуры из фундаментной плиты нет: плита лежит на "
        "утеплителе XPS и как заземлитель не работает — это исправлено по предыдущему "
        "замечанию посёлка. Сопротивление заземляющего устройства проверяется замером после "
        "монтажа. Если выпуски от свай согласовать со Строй Хауз не удастся, наружного "
        "контура достаточно — его увеличат по результату замера.")

    # 5 ------------------------------------------------------------------------------------------
    d.h1("5. Водоподготовка и место под неё")
    d.p("Узел ввода и водоподготовка заложены в 291-ВК, место — в котельной у стены по оси 11. "
        "Состав по ходу воды: кран → счётчик с импульсным выходом → сетчатый фильтр 100 мкм → "
        "редуктор 3,5 бар и обратный клапан → фильтр 20 мкм → умягчение (резерв места "
        "1,2 × 0,6 м) → бойлер ГВС; отдельно — обратный осмос 50–100 л/ч с баком 50 л для "
        "питьевой воды и пароувлажнителей. Защита от протечек с электрокраном на вводе.")
    d.p("Чего пока нет — анализа воды. Дом подключается к сетям посёлка, и состав установки "
        "(нужны ли обезжелезивание и умягчение, их размер) зависит от качества воды в "
        "посёлковой сети. Просим посёлок передать протокол анализа воды (железо, марганец, "
        "жёсткость, мутность, перманганатная окисляемость) и гарантированное давление на вводе. "
        "Если по анализу понадобятся две колонны (обезжелезивание + умягчение) с солевым баком, "
        "места в котельной 11,2 м² не хватит рядом с котлами и баками — тогда установка "
        "переносится в соседнюю постирочную (9 м²) или в хозблок.")

    # 6 ------------------------------------------------------------------------------------------
    d.h1("6. Основание под камин и дымоходы")
    d.p("Согласны, это нужно решить до бетонирования плиты. В доме два дымохода: дровяной "
        "камин в гостиной у оси 7 (дымоход Ø200 через кровлю) и дымоход пеллетного котла "
        "в котельной у осей 13/Д. В расчёте плиты и свай Строй Хауз камин не учтён — "
        "в перечне нагрузок РПЗ КЖ0 его нет.")
    d.table([
        ("Вариант", "Масса, т", "Нагрузка", "Что нужно"),
        ("Кирпичный камин и кирпичная труба высотой 8–9 м", "5–6", "≈ 60–70 кН на площадку "
         "≈ 1,0 × 1,5 м; сваи у оси 7 уже нагружены на 107–129 кН из 141,7 допустимых",
         "Отдельное основание: 2–4 дополнительные сваи или локальное утолщение плиты — "
         "в КЖ0 до бетонирования плиты (по графику до 25.12.2026)"),
        ("Стальная топка с облицовкой и стальной дымоход-сэндвич", "1–1,5", "≈ 10–15 кН, "
         "распределяется на 2–3 м² плиты", "Проверка плиты проектировщиком; дополнительные "
         "сваи, как правило, не нужны"),
        ("Дымоход котла: сэндвич Ø150/250 в коробе 450×450", "0,2–0,3", "опора на плиту "
         "в котельной", "Проверка не требуется; проходки в перекрытии и кровле — в КД4/КД5"),
    ], [2.6, 0.8, 3.0, 3.4])
    d.p("Решение заказчика: тип камина выбрать до 10.11.2026. Если камин кирпичный — "
        "Строй Хауз до бетонирования плиты добавляет в КЖ0 сваи или утолщение плиты под "
        "камин по нагрузке от поставщика камина. В брусовом доме кирпичный дымоход не "
        "связывается со стенами, перекрытием и кровлей жёстко: брус садится на 3–5 %, поэтому "
        "проходки делаются со скользящим узлом. Разделки и отступки до деревянных конструкций — "
        "по СП 7.13130. Пункт добавлен в перечень запросов к Строй Хауз.")

    d.h1("Что просим у посёлка")
    d.items([
        "Протокол анализа воды из посёлковой сети и гарантированное давление на вводе.",
        "Планы по посёлковой ДГУ: будет ли резерв и какой мощности на дом.",
        "Лимит электрической мощности на дом (запрошено 40–50 кВт, в проекте принято 30 кВт).",
    ], numbered=True)

    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, "Ответы на вопросы посёлка по инженерным разделам.pdf")
    d.pdf(path, footer="Дом «Ромарио» · ответы на вопросы посёлка · 21.10.2026")
    return d


if __name__ == "__main__":
    build()
