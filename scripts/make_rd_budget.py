def k(x):
    """₽ → тыс. ₽, округление до 10 тыс."""
    return int(round(x / 1000, -1))


def fk(x):
    return f"{k(x):,}".replace(",", " ")


def fr(x):
    return f"{x:,.0f}".replace(",", " ")


def ft(x):
    """₽ → тыс. ₽ без округления до десятков (для позиций)."""
    return f"{x / 1000:,.0f}".replace(",", " ") if x >= 500 or x == 0 else f"{x / 1000:.1f}".replace(".", ",")


def short(name, n=95):
    return name if len(name) <= n else name[:name.rfind(" ", 0, n)].rstrip(",") + "…"


def fq(q):
    return f"{q:g}".replace(".", ",")


