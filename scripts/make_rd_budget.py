def to_csv(T):
    b = io.StringIO()
    w = csv.writer(b)
    w.writerow(["Раздел / статья", "Мин., тыс. ₽", "Макс., тыс. ₽", "Газ этап 2, тыс. ₽"])
    t1 = [0, 0]
    for c in CODES:
        t = T[c]
        t1[0] += t["total"][0]
        t1[1] += t["total"][1]
        g = f"{k(t['gas'][0])}–{k(t['gas'][1])}" if t["gas"][1] else ""
        w.writerow([f"{c} {TITLES[c]}".upper(), k(t["total"][0]), k(t["total"][1]), g])
        if c == "291-НС":
            for n, lo, hi, tag in NS:
                w.writerow(["   " + n, k(lo), k(hi), ""])
        else:
            for n, lo, hi in t["lines"]:
                w.writerow(["   " + n, k(lo), k(hi), ""])
    w.writerow(["ИТОГО по разделам РД (этап 1)", k(t1[0]), k(t1[1]), ""])
    return b.getvalue()


