def match(code, name):
    for p in PRICES[code]:
        if p[0] in name:
            return p
    raise KeyError(f"{code}: нет цены для «{name}»")


def section(code):
    """Строки сметы раздела: (блок, наименование, ед., кол-во, цена мин, цена макс, сумма мин, макс, метка)."""
    rows, block = [], ""
    for r in SPEC[code].spec_rows():
        if r[0] == "#":
            block = r[1]
            continue
        name, unit, qty = r[1], r[3], float(r[4])
        p = match(code, name)
        tag = p[3] if len(p) > 3 else None
        if callable(p[1]):
            lo, hi = p[1](name)
        else:
            lo, hi = p[1], p[2]
        rows.append(dict(block=block, name=name, unit=unit, qty=qty, lo=lo, hi=hi,
                         slo=lo * qty, shi=hi * qty, tag=tag))
    return rows


def totals(code, exclude=()):
    """Итоги раздела по статьям: материалы, монтаж, расходники, ПНР (этап 1 и этап 2 отдельно).
    exclude — начала наименований позиций, которые считаются отдельным блоком (например, свет)."""
    if code == "291-НС":
        lines = [(n, lo, hi) for n, lo, hi, t in NS if t is None]
        st2 = [(n, lo, hi) for n, lo, hi, t in NS if t == GAS]
        opt = [(n, lo, hi) for n, lo, hi, t in NS if t == "option"]
        s = lambda xs, i: sum(x[i] for x in xs)
        return dict(lines=[("Сети и подключения (материалы и работы)", s(lines, 1), s(lines, 2))],
                    total=(s(lines, 1), s(lines, 2)), gas=(s(st2, 1), s(st2, 2)),
                    option=(s(opt, 1), s(opt, 2)), equip=(0, 0))
    rows = [r for r in section(code) if not r["name"].startswith(tuple(exclude))]
    w = WORK[code]
    st1 = [r for r in rows if r["tag"] is None]
    st2 = [r for r in rows if r["tag"] == GAS]
    mat = (sum(r["slo"] for r in st1), sum(r["shi"] for r in st1))
    if isinstance(w["mount"], dict):
        def kb(block):
            return next(v for key, v in w["mount"].items() if block.startswith(key))
        mount = (sum(r["slo"] * kb(r["block"])[0] for r in st1),
                 sum(r["slo"] * kb(r["block"])[1] for r in st1))
    else:
        mount = (mat[0] * w["mount"][0], mat[0] * w["mount"][1])
    cons = (mat[0] * w["cons"][0], mat[0] * w["cons"][1])
    lines = [("Оборудование и материалы по спецификации", *mat),
             ("Монтажные работы", *mount),
             ("Крепёж, расходники, доставка", *cons)]
    for n, lo, hi in w.get("extra", []):
        lines.append((n, lo, hi))
    lines.append((w["pnr_name"], *w["pnr"]))
    tot = (sum(x[1] for x in lines), sum(x[2] for x in lines))
    g = (sum(r["slo"] for r in st2) * 1.3, sum(r["shi"] for r in st2) * 1.45)
    big = sorted(st1, key=lambda r: -(r["slo"] + r["shi"]))[:3]
    return dict(lines=lines, total=tot, gas=g, option=(0, 0), equip=mat, top=big, rows=rows)


