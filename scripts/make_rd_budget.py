def xlsx(path, T):
    wb = Workbook()
    thin = Side(style="thin")
    brd = Border(left=thin, right=thin, top=thin, bottom=thin)
    hdr = PatternFill("solid", fgColor="DDDDDD")
    ws = wb.active
    ws.title = "Сводка"
    ws.append(["Раздел", "Этап 1 мин., тыс. ₽", "Этап 1 макс., тыс. ₽", "Среднее, тыс. ₽",
               "Газ этап 2 мин.", "Газ этап 2 макс."])
    sheet_refs = []
    for c in CODES:
        nm = c.replace("291-", "")
        ws2 = wb.create_sheet(nm.replace(".", "-"))
        ws2.append(["Позиция", "Ед.", "Кол-во", "Цена мин., ₽", "Цена макс., ₽", "Сумма мин., ₽",
                    "Сумма макс., ₽", "Примечание"])
        if c == "291-НС":
            for n, lo, hi, tag in NS:
                r = ws2.max_row + 1
                ws2.append([n, "компл.", 1, lo, hi, f"=C{r}*D{r}", f"=C{r}*E{r}",
                            {GAS: "этап 2", "option": "опция, не в итоге"}.get(tag, "")])
            last = ws2.max_row
            tot = ws2.max_row + 1
            ws2.append(["ИТОГО этап 1", None, None, None, None,
                        f'=SUMIF(H2:H{last},"",F2:F{last})', f'=SUMIF(H2:H{last},"",G2:G{last})'])
            gas = (f"=SUMIF('{ws2.title}'!H2:H{last},\"этап 2\",'{ws2.title}'!F2:F{last})/1000",
                   f"=SUMIF('{ws2.title}'!H2:H{last},\"этап 2\",'{ws2.title}'!G2:G{last})/1000")
        else:
            t = T[c]
            w = WORK[c]
            for r_ in t["rows"]:
                r = ws2.max_row + 1
                note = {"client": "поставка заказчика", GAS: "этап 2"}.get(r_["tag"], "")
                ws2.append([r_["name"], r_["unit"], r_["qty"], r_["lo"], r_["hi"], f"=C{r}*D{r}",
                            f"=C{r}*E{r}", note])
            last = ws2.max_row
            m = ws2.max_row + 1
            ws2.append(["Материалы и оборудование (этап 1)", None, None, None, None,
                        f'=SUMIF(H2:H{last},"",F2:F{last})', f'=SUMIF(H2:H{last},"",G2:G{last})'])
            for n, lo, hi in t["lines"][1:]:
                r = ws2.max_row + 1
                ws2.append([n, None, None, None, None, round(lo), round(hi), "оценка"])
            tot = ws2.max_row + 1
            ws2.append(["ИТОГО этап 1", None, None, None, None, f"=SUM(F{m}:F{tot - 1})",
                        f"=SUM(G{m}:G{tot - 1})"])
            gas = (round(t["gas"][0] / 1000), round(t["gas"][1] / 1000))
        for cell in ws2[1]:
            cell.font = Font(bold=True)
            cell.fill = hdr
        for cell in ws2[tot]:
            cell.font = Font(bold=True)
        ws2.column_dimensions["A"].width = 80
        for col in "BCDEFG":
            ws2.column_dimensions[col].width = 13
        ws2.column_dimensions["H"].width = 20
        for row in ws2.iter_rows(min_row=1, max_row=ws2.max_row):
            for cell in row:
                cell.border = brd
                cell.alignment = Alignment(wrap_text=True, vertical="center")
