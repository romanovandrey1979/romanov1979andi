def group_table(ax, x, y, panel, sec=None):
    rows = [("№", "Наименование", "Pу, кВт", "Фаза", "Автомат", "УЗО / АВДТ", "Кабель", "Секция")]
    gs = [g for g in E.GROUPS if g["panel"] == panel and (sec is None or g["sec"] == sec)]
    for i, g in enumerate(gs, 1):
        rows.append((f"{panel[:3]}-{i}", wrap(g["name"], 62), f"{g['p']:.2f}".replace(".", ","),
                     g["phase"], g["br"], wrap(g["prot"], 24), wrap(g["cab"], 34),
                     {"общая": "О", "гарантированная": "Г", "бесперебойная": "Б"}[g["sec"]]))
    return table(ax, x, y, [14, 104, 13, 10, 18, 34, 58, 12], rows, rh=4.2, fs=4.6)


