def p1_heater():
    """Температура после ротора и расчётная мощность догрева П1 (кВт)."""
    t_after = CLIMATE["t_winter"] + ETA_ROTOR * (22 - CLIMATE["t_winter"])
    return t_after, heater_kw(TOT["П1"], t_after, CLIMATE["t_supply"])


