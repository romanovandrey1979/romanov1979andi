"""Сводные данные по системам и спецификация оборудования (ГОСТ 21.110)."""
import math
from ovk_data import (calc_air, system_totals, calc_cooling, duct_d, heater_kw, CLIMATE,
                      HOOD_FLOW, HOOD_COMP)

ROOMS = calc_air()
TOT = system_totals(ROOMS)
AC = calc_cooling(ROOMS)

ETA_ROTOR = 0.75     # температурная эффективность роторного рекуператора при tн=-25 °C
TUBE_FLOW = 35       # м³/ч на один гибкий воздуховод Ø90 (лучевая разводка 1 этажа)


def p1_heater():
    t_after = CLIMATE["t_winter"] + ETA_ROTOR * (22 - CLIMATE["t_winter"])
    return t_after, heater_kw(TOT["П1"], t_after, CLIMATE["t_supply"])


def p2_heater():
    return heater_kw(HOOD_COMP, CLIMATE["t_winter"], 16)


def tubes(flow):
    return max(1, math.ceil(flow / TUBE_FLOW))


def ac_systems():
    k1 = [a for a in AC if a["floor"] == 1]
    k2 = [a for a in AC if a["floor"] == 2]
    std_out = [12.1, 14.0, 15.5, 22.4, 25.2, 28.0, 33.5]
    res = []
    for name, lst in (("К1", k1), ("К2", k2)):
        q = sum(a["q"] for a in lst)
        q_div = q * 0.85  # коэффициент одновременности
        units = sum(a["unit"] for a in lst)
        out = next(o for o in std_out if o >= q_div and units / o <= 1.3)
        res.append(dict(sys=name, units=lst, q=round(q, 2), q_div=round(q_div, 2),
                        sum_units=round(units, 1), outdoor=out,
                        ratio=round(units / out * 100)))
    return res


AC_SYS = ac_systems()

# Для разводки гибкими трубами по 1 этажу и разводки круглыми по 2 этажу
def branch_info(r, flow, floor):
    if floor == 1:
        n = tubes(flow)
        return f"Ø90 × {n}", n
    d, v = duct_d(flow, 3.0)
    return f"Ø{d}", 1


def p1_rooms(floor):
    return [r for r in ROOMS if r["sup_sys"] == "П1" and r["floor"] == floor]


def v1_rooms(floor):
    # холл-лестница (второй свет) — вытяжка из верхней зоны через чердак, отнесена к «2 этажу»
    out = []
    for r in ROOMS:
        if r["exh_sys"] != "В1":
            continue
        f = 2 if r["kind"] == "stair" else r["floor"]
        if f == floor:
            out.append(r)
    return out


