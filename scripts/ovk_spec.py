def p2_heater():
    return heater_kw(HOOD_COMP, CLIMATE["t_winter"], 16)


def ac_systems():
    k1 = [a for a in AC if a["floor"] == 1]
    k2 = [a for a in AC if a["floor"] == 2]
    std_out = [12.1, 14.0, 15.5, 18.0, 20.0, 22.4, 25.2, 28.0, 33.5]
    res = []
    for name, lst in (("К1", k1), ("К2", k2)):
        q = sum(a["q"] for a in lst)
        q_div = q * 0.85  # коэффициент одновременности
        units = sum(a["unit"] for a in lst)
        # наружный блок не меньше суммы внутренних (загрузка ≤ 100 %, допускается до 130 % по ПО)
        out = next(o for o in std_out if o >= q_div and o >= units * 0.99)
        res.append(dict(sys=name, units=lst, q=round(q, 2), q_div=round(q_div, 2),
                        sum_units=round(units, 1), outdoor=out,
                        ratio=round(units / out * 100)))
    return res


AC_SYS = ac_systems()

# 1 этаж — от шахт ВК-1/ВК-4 по подшивным потолкам к щелевым диффузорам у стен;
# 2 этаж — потолочные диффузоры прямо от чердачных магистралей
def branch_info(r, flow, floor):
    d, v = duct_d(flow, 3.0)
    if floor == 1:
        n = max(1, round(flow / 90))
        return f"Ø{d}, щел. ×{n}", n
    return f"Ø{d}", 1


def p1_rooms(floor):
    return [r for r in ROOMS if r["sup_sys"] == "П1" and r["floor"] == floor]


def v1_rooms(floor):
    # холл-лестница (второй свет) — вытяжка из верхней зоны через чердак, отнесена к «2 этажу»
    out = []
    for r in ROOMS:
        if r["exh_sys"] != "В1":
            continue
        f = 2 if r["kind"] == "stair" else r["floor"]
        if f == floor:
            out.append(r)
    return out


