LUM_FLUX = 1500        # лм, условный светильник LED 15 Вт
LUM_W = 15
U_KZ = 0.55 / 1.25     # коэффициент использования / коэффициент запаса


def lux_for(name):
    for k, v in LUX.items():
        if k.lower() in name.lower():
            return v
    return 100


def sockets_for(fl, num, name, area, perim):
    n = name.lower()
    if "кухня" in n:
        return 8
    if "с/у" in n or "душев" in n:
        return 2
    if "сауна" in n:
        return 0
    if "котельная" in n:
        return 3
    if "кладов" in n or "гардероб" in n:
        return 1
    if "холл" in n or "прихож" in n or "лестнич" in n:
        return 3
    if "постироч" in n:
        return 4
    return max(4, math.ceil(perim / 4) + 1)


