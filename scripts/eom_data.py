def on_brus(floor, x, y, tol=350):
    for x0, y0, x1, y1, ax in BRUS[floor]:
        if x0 == x1 and abs(x - x0) <= tol and min(y0, y1) - 1 <= y <= max(y0, y1) + 1:
            return ax, x0, y0, y1, "v"
        if y0 == y1 and abs(y - y0) <= tol and min(x0, x1) - 1 <= x <= max(x0, x1) + 1:
            return ax, y0, x0, x1, "h"
    return None


def nearest_axis(val, axes):
    k = min(axes, key=lambda a: abs(axes[a] - val))
    return k, val - axes[k]


def perimeter_points(geom, n, inset=250):
    """n точек равномерно по периметру помещения (по часовой, от середины нижней стены)."""
    x0, y0, x1, y1 = geom
    x0, y0, x1, y1 = x0 + inset, y0 + inset, x1 - inset, y1 - inset
    w, h = x1 - x0, y1 - y0
    P = 2 * (w + h)
    pts = []
    for i in range(n):
        t = ((i + 0.5) / n * P + w / 2) % P
        if t < w:
            pts.append((x0 + t, y0))
        elif t < w + h:
            pts.append((x1, y0 + (t - w)))
        elif t < 2 * w + h:
            pts.append((x1 - (t - w - h), y1))
        else:
            pts.append((x0, y1 - (t - 2 * w - h)))
    return pts


def lum_points(geom, n):
    x0, y0, x1, y1 = geom
    w, h = x1 - x0, y1 - y0
    cols = max(1, round(math.sqrt(n * w / max(h, 1))))
    rows = math.ceil(n / cols)
    pts = []
    for i in range(n):
        r, c = divmod(i, cols)
        pts.append((x0 + w * (c + 0.5) / cols, y0 + h * (r + 0.5) / rows))
    return pts


HALL_NODE = {1: (12000, 7300), 2: (12000, 8500)}


def switch_point(geom, floor):
    x0, y0, x1, y1 = geom
    hx, hy = HALL_NODE[floor]
    cx, cy = min(max(hx, x0 + 300), x1 - 300), min(max(hy, y0 + 300), y1 - 300)
    d = {"l": abs(cx - x0), "r": abs(x1 - cx), "b": abs(cy - y0), "t": abs(y1 - cy)}
    side = min(d, key=d.get)
    return {"l": (x0 + 150, cy), "r": (x1 - 150, cy), "b": (cx, y0 + 150),
            "t": (cx, y1 - 150)}[side]


