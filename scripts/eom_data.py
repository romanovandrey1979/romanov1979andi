def balance():
    ph = {"A": 0.0, "B": 0.0, "C": 0.0}
    for g in GROUPS:
        if g["p"] == 0:
            g["phase"] = "ABC" if g["ph"] == 3 else "—"
            continue
        if g["ph"] == 3:
            g["phase"] = "ABC"
            for k in ph:
                ph[k] += g["p"] / 3
        else:
            k = min(ph, key=ph.get)
            g["phase"] = k
            ph[k] += g["p"]
    return ph


