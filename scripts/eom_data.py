def perimeter_points(geom, n, inset=250):
    """n точек равномерно по периметру помещения (условное размещение до карты дизайнера)."""
    x0, y0, x1, y1 = geom
    x0, y0, x1, y1 = x0 + inset, y0 + inset, x1 - inset, y1 - inset
    w, h = x1 - x0, y1 - y0
    P = 2 * (w + h)
    pts = []
    for i in range(n):
        t = ((i + 0.5) / n * P + w / 2) % P
        if t < w:
            pts.append((x0 + t, y0))
        elif t < w + h:
            pts.append((x1, y0 + (t - w)))
        elif t < 2 * w + h:
            pts.append((x1 - (t - w - h), y1))
        else:
            pts.append((x0, y1 - (t - 2 * w - h)))
    return pts


HALL_NODE = {1: (12000, 7300), 2: (12000, 8500)}


def switch_point(geom, floor):
    x0, y0, x1, y1 = geom
    hx, hy = HALL_NODE[floor]
    cx, cy = min(max(hx, x0 + 300), x1 - 300), min(max(hy, y0 + 300), y1 - 300)
    d = {"l": abs(cx - x0), "r": abs(x1 - cx), "b": abs(cy - y0), "t": abs(y1 - cy)}
    side = min(d, key=d.get)
    return {"l": (x0 + 150, cy), "r": (x1 - 150, cy), "b": (cx, y0 + 150),
            "t": (cx, y1 - 150)}[side]


