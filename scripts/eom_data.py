def build_points():
    pts = []   # (этаж, x, y, тип, помещение)
    for r in ROOMS:
        g = r["geom"]
        kitchen = "кухня" in r["name"].lower()
        for x, y in perimeter_points(g, r["n_sock"]):
            pts.append((r["floor"], x, y, "РК" if kitchen else "Р", f"{r['num']}. {r['name']}"))
        if "сауна" not in r["name"].lower():
            x, y = switch_point(g, r["floor"])
            pts.append((r["floor"], x, y, "В", f"{r['num']}. {r['name']}"))
    for fl, x, y, t, d in OUTDOOR:
        pts.append((fl, x, y, t, d))
    return pts


def holes(points):
    out = []
    for fl, x, y, t, room in points:
        hit = on_brus(fl, x, y)
        if not hit:
            continue
        ax, pos, a0, a1, orient = hit
        along = y if orient == "v" else x
        ref, off = nearest_axis(along, AXES_Y if orient == "v" else AXES_X)
        level = (0 if fl == 1 else 4500) + H_POINT[t]
        out.append(dict(floor=fl, axis=ax, ref=ref, off=round(off / 10) * 10,
                        h=H_POINT[t], abs_h=level, type=t, room=room, x=x, y=y))
    return out


POINTS = build_points()
HOLES = holes(POINTS)

