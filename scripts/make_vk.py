def devices(pred=lambda f: True):
    return [f for fl in FIX.values() for f in fl if pred(f)]


def flow(n, hot=False):
    """Секундный расход q = 5·q0·α по СП 30, прил. А; n — число приборов на участке."""
    q0 = H.Q0_H if hot else H.Q0_TOT
    qhr = H.Q_HR_U_H if hot else H.Q_HR_U_TOT
    n_all = len(devices(lambda f: f[2] not in DRY and (not hot or f[2] in HOT)))
    p = qhr * H.PEOPLE / (q0 * n_all * 3600)
    a = H.alpha(n * p)
    return 5 * q0 * a, p, a


def velocity(q_ls, pipe):
    d = PIPE_ID[pipe] / 1000
    return q_ls / 1000 / (math.pi * d * d / 4)


def calc():
    n_w = len(devices(lambda f: f[2] not in DRY))
    n_h = len(devices(lambda f: f[2] in HOT))
    q, p, a = flow(n_w)
    qh, ph, ah = flow(n_h, True)
    return dict(N=n_w, Nh=n_h, P=p, Ph=ph, NP=n_w * p, NPh=n_h * ph, alpha=a, alpha_h=ah,
                q_tot=q, q_h=qh, q_s=q + 1.6, day_tot=H.PEOPLE * H.Q_U_DAY / 1000,
                day_h=H.PEOPLE * H.Q_U_DAY_H / 1000)


