def ortho(ax, a, b, color, lw=1.0, ls="-", z=4, mode="hv"):
    mid = (b[0], a[1]) if mode == "hv" else (a[0], b[1])
    xs, ys = zip(*[S(p) for p in (a, mid, b)])
    ax.plot(xs, ys, c=color, lw=lw, ls=ls, zorder=z)


def stack(ax, name, pt, color=BROWN, label=True):
    x, y = S(pt)
    ax.add_patch(Circle((x, y), 1.6, fc=color, ec="k", lw=0.5, zorder=8))
    if label:
        ax.text(x + 2, y + 1.5, name, fontsize=4.4, color=color, weight="bold", zorder=9,
                bbox=dict(fc="white", ec="none", pad=0.1, alpha=0.85))


