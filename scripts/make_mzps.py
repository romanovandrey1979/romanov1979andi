def det_symbol(ax, x, y, kind):
    c = {"Д": RED, "Т": ORANGE, "CO": BROWN}[kind]
    ax.add_patch(Circle((x, y), 1.8, fc="white", ec=c, lw=1, zorder=8))
    ax.text(x, y, kind, ha="center", va="center", fontsize=3.8, color=c, weight="bold", zorder=9)


def sheet_ps(pdf, n, floor):
    fig, ax = new_sheet(n, SHEETS[n - 1])
    draw_underlay(ax, 4 if floor == 1 else 5)
    title(ax, f"План {floor} этажа{' и чердака' if floor == 2 else ''}. Пожарная сигнализация "
              "(М 1:100)")
    for (fl, num), kinds in DET.items():
        if fl != floor:
            continue
        x0, y0, x1, y1 = GEOM[(fl, num)]
        for i, k in enumerate(kinds):
            fx = x0 + (x1 - x0) * (i + 1) / (len(kinds) + 1)
            fy = y0 + (y1 - y0) * 0.62
            det_symbol(ax, *S((fx, fy)), k)
    if floor == 1:
        hx, hy = S(HUB)
        ax.add_patch(Rectangle((hx - 3, hy - 2), 6, 4, fc="#e8f5e9", ec="k", lw=0.8, zorder=9))
        ax.text(hx, hy, "ПКП", ha="center", va="center", fontsize=4.4, weight="bold", zorder=10)
        ax.text(hx + 4, hy - 4, "Централь (хаб) GSM/Wi-Fi,\nреле откл. П1В1, П2", fontsize=4.2,
                zorder=10, bbox=dict(fc="white", ec="none", pad=0.1, alpha=0.85))
    else:
        sx, sy = S(SIREN)
        ax.add_patch(Rectangle((sx - 2.5, sy - 2), 5, 4, fc="#ffebee", ec="k", lw=0.8, zorder=9))
        ax.text(sx, sy, "ОЗ", ha="center", va="center", fontsize=4.2, weight="bold", zorder=10)
        for x, y, k in ATTIC_DET:
            px, py = S((x, y))
            ax.add_patch(Circle((px, py), 2.6, fc="none", ec=GRAY, lw=0.8, ls="--", zorder=8))
            det_symbol(ax, px, py, k)
            ax.text(px + 3, py - 3, "чердак", fontsize=4.2, color=GRAY, zorder=9)
    y = 288
    ax.text(333, y, "Условные обозначения", fontsize=6.5, weight="bold")
    y -= 6
    for k, t in (("Д", "Извещатель дымовой оптико-электронный"),
                 ("Т", "Извещатель тепловой максимально-дифф."), ("CO", "Датчик угарного газа")):
        det_symbol(ax, 339, y, k)
        ax.text(345, y, t, fontsize=5.2, va="center")
        y -= 5.5
    ax.text(333, y, "ПКП — централь, ОЗ — оповещатель (сирена)", fontsize=5.2)
    notes(ax, 333, y - 6, [
        "Извещатели — радиоканальные, с питанием от батарей (срок ≥ 5 лет), тестирование "
        "раз в 6 месяцев.",
        "Дымовые — на потолке ≥ 0,5 м от стен, балок и диффузоров вентиляции.",
        "В зоне второго света холла — дымовой извещатель на потолке 2 этажа.",
        "При сработке: сирена, push/SMS владельцу, отключение П1В1 и П2.",
    ])
    pdf.savefig(fig)
    plt.close(fig)


