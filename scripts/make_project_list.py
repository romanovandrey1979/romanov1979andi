def footer(canvas, doc):
    canvas.saveState()
    canvas.setFont("DV", 7.5)
    canvas.setFillColor(colors.grey)
    canvas.drawString(15 * mm, 9 * mm, "Дом «Берта Ромарио» — перечень проектной документации")
    canvas.drawRightString(A4[0] - 15 * mm, 9 * mm, f"стр. {doc.page}")
    canvas.restoreState()


def build(path):
    doc = SimpleDocTemplate(path, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=14 * mm, bottomMargin=16 * mm,
                            title="Перечень проектов — дом «Берта Ромарио»")
    s = [Paragraph("Перечень проектов для строительства дома «Берта Ромарио»", H1),
         Paragraph("Индивидуальный жилой дом из клееного бруса, 488 м², Московская обл., "
                   "Истринский р-н, д. Веледниково", P),
         Paragraph("Для ИЖС проектная документация по закону не обязательна (ч. 3 ст. 48 ГрК РФ): "
                   "строительство ведётся по уведомлению. Но проекты нужны для подключения газа и "
                   "электричества, для ипотеки и банковского финансирования, а также чтобы сметы "
                   "и стройка не расходились. Ниже — полный рабочий набор для дома такого уровня.",
                   P)]
    leg = [[Paragraph(f"<b>{v[0]}</b>", C) for v in STATUS.values()]]
    lt = Table(leg, colWidths=[45 * mm] * 4)
    lt.setStyle(TableStyle([("BACKGROUND", (i, 0), (i, 0), v[1])
                            for i, v in enumerate(STATUS.values())] +
                           [("BOX", (0, 0), (-1, -1), 0.4, colors.grey),
                            ("INNERGRID", (0, 0), (-1, -1), 0.4, colors.grey),
                            ("ALIGN", (0, 0), (-1, -1), "CENTER")]))
    s += [Spacer(1, 3), lt]

    for title, rows in SECTIONS:
        data = [[Paragraph("Документ / раздел", CB), Paragraph("Статус", CB),
                 Paragraph("Что нужно / комментарий", CB)]]
        style = [("BOX", (0, 0), (-1, -1), 0.5, colors.grey),
                 ("INNERGRID", (0, 0), (-1, -1), 0.3, colors.grey),
                 ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e8e8e8")),
                 ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                 ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]
        for i, (name, st, note) in enumerate(rows, 1):
            data.append([Paragraph(name, C), Paragraph(STATUS[st][0], C), Paragraph(note, C)])
            style.append(("BACKGROUND", (1, i), (1, i), STATUS[st][1]))
        t = Table(data, colWidths=[68 * mm, 30 * mm, 82 * mm], repeatRows=1)
        t.setStyle(TableStyle(style))
        s += [KeepTogether([Paragraph(title, H2), t])]

    s.append(Paragraph("Что нужно от заказчика, чтобы двигаться дальше", H2))
    s += [Paragraph(f"{i}. {t}", P) for i, t in enumerate(NEEDS, 1)]
    s.append(Paragraph("Что можно начать прямо сейчас", H2))
    s += [Paragraph(f"{i}. {t}", P) for i, t in enumerate(NOW, 1)]
    s.append(Spacer(1, 4))
    s.append(Paragraph("Важно: разделы, подготовленные с помощью Claude, — рабочие проекты для "
                       "стройки без подписи и печати проектной организации. Для газа это "
                       "обязательно, а для банка или экспертизы их нужно проверить у инженера, "
                       "который их подпишет. Рекомендуемый порядок работ: отопление → ВК → ЭОМ.",
                       P))
    doc.build(s, onFirstPage=footer, onLaterPages=footer)


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else "Перечень проектов.pdf")
