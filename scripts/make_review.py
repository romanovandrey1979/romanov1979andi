SCEN = E.load_scenarios()
i3 = E.i3
P_TOTAL_INST = E.P_INST
LIMIT_KW = 30


def f1(x):
    return f"{x:.1f}".replace(".", ",")


def loads_doc():
    d = Doc("Расчёт электрических нагрузок — дом «Ромарио»",
            "Концепт заказчика. Перечень потребителей — по 291-ЭОМ (секции ГРЩ: общая, "
            "гарантированная от генератора, бесперебойная от батареи). Pр = Σ Pу·Кс по режимам.")
    d.h1("1. Потребители")
    rows = [("Потребитель", "Pу, кВт", "Фазы", "Секция", "Кс зима день / ночь / лето")]
    for c in E.CONSUMERS:
        rows.append((c["name"], f1(c["p_kw"]), c["phases"], c["section"],
                     " / ".join(f"{k:g}".replace(".", ",") for k in c["kc"])))
    rows.append(("Установленная мощность", f1(P_TOTAL_INST), "", "", ""))
    d.table(rows, [5.5, 1, 0.7, 1.6, 2.2], bold_last=True)
    d.h1("2. Расчётная мощность по режимам")
    rows = [("Режим", "Pр, кВт", "I, А (3ф)")]
    for nm, p in SCEN:
        rows.append((nm, f1(p), f"{i3(p):.0f}"))
    d.table(rows, [6, 1, 1])
    d.h1("3. Мощность на дом")
    d.items([
        f"Лимит на дом от посёлковой ТП не утверждён; в расчётах принято {LIMIT_KW} кВт, 3 фазы "
        "(запрошено 40–50 кВт; ответ управляющего ожидался к 24.10, ТУ — к 16.11).",
        "Все режимы укладываются в 30 кВт за счёт ступеней электрокотла, ночного тарифа и "
        "ограничителя нагрузки с приоритетами (котельная, холодильники, свет).",
        "Вводной автомат 3P 50 А, ограничитель нагрузки на 45 А; при выделении 40–50 кВт — "
        "пересчёт ввода и питающих линий.",
        "Резерв: посёлковый генератор (решение не принято) + свой генератор 8–10 кВт с АВР "
        "(секции «гарантированная» и «бесперебойная») + батарея 15 кВт·ч с инвертором.",
        "На период стройки — 15 кВт (щит Строй Хауз).",
    ])
    return d


