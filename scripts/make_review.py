KO = 0.8   # коэффициент одновременности бытовых групп


def scenario(season, reserve=False, lm=False, gas=False):
    b = h = 0.0
    for g, nm, pu, kc, s, t in LOADS:
        on = (season in s) or (s == "WS")
        if s == "R":
            on = reserve
        if gas and "Пеллетный" in nm:
            on = False
        if reserve and "Пеллетный" in nm:
            on = False
        if lm and reserve and ("сауны" in nm or "П2: электронагр" in nm):
            on = False
        if not on:
            continue
        if t == "B":
            b += pu * kc
        else:
            h += pu * kc
    return b * KO + h


def i3(p):
    return p * 1000 / (math.sqrt(3) * 380 * 0.95)


