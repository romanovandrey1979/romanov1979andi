def make_xlsx():
    wb = Workbook()
    ws = wb.active
    ws.title = "Позиции"
    ws.append(["КП", "Объект", "Раздел", "Сумма, ₽", "Строка ТЗ (дубль)"])
    for r in ROWS:
        ws.append(list(r) + ["да" if r[2].startswith("Составление ТЗ") else ""])
    last = ws.max_row
    ws.append(["", "", "ИТОГО", f"=SUM(D2:D{last})", ""])
    ws.append(["", "", "в т. ч. «составление ТЗ»", f'=SUMIF(E2:E{last},"да",D2:D{last})', ""])
    for row in ws.iter_rows(min_row=2, min_col=4, max_col=4):
        for c in row:
            c.number_format = "#,##0"
    for c in ws[1]:
        c.fill, c.font = HDR, Font(bold=True)
    for col, w in zip("ABCDE", (6, 16, 70, 14, 16)):
        ws.column_dimensions[col].width = w
    w2 = wb.create_sheet("Реестр")
    w2.append(["Код", "Файл", "Что", "Дата", "Сумма, ₽", "Условия"])
    for k, v in KP.items():
        w2.append([k, v[0], v[1], v[2], tot(lambda r, k=k: r[0] == k), v[3]])
    w3 = wb.create_sheet("Цель")
    w3.append(["Лот", "По КП, ₽", "Цель от, ₽", "Цель до, ₽", "Что меняем"])
    for a, b, c, e in TARGET:
        w3.append([a, b, c[0], c[1], e])
    for s in (w2, w3):
        for c in s[1]:
            c.fill, c.font = HDR, Font(bold=True)
        for row in s.iter_rows():
            for c in row:
                c.border = B
                c.alignment = Alignment(wrap_text=True, vertical="top")
                if isinstance(c.value, int):
                    c.number_format = "#,##0"
        for col, w in zip("ABCDEF", (30, 36, 40, 14, 14, 50)):
            s.column_dimensions[col].width = w
    wb.save(out("Реестр КП — инженерные системы.xlsx"))


